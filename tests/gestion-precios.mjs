import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=read('index.html'),dir=read('servicios.html'),app=read('app.js');
const panel=read('gestion.html'),panelJS=read('gestion.js'),cfg=read('bn-config.js'),live=read('catalogo-live.js');
const sql=read('supabase/bn_prices_schema.sql'),seed=read('supabase/bn_prices_seed.sql'),build=read('build.sh');
assert(html.includes('id="mapFrame"')&&html.includes('id="mapOpen"'),'Conservar mapa interactivo existente');
assert(app.includes("getElementById('mapOpen')"),'Conservar funcionamiento del mapa');
assert(html.includes('/bn-config.js')&&html.includes('/catalogo-live.js'),'Falta conexión progresiva en portada');
assert(dir.includes('/bn-config.js')&&dir.includes('/catalogo-live.js'),'Falta conexión progresiva en servicios');
assert((dir.match(/data-service-id="s\d{2}"/g)||[]).length===27,'Faltan IDs para 27 servicios');
assert((dir.match(/itemtype="https:\/\/schema.org\/Service"/g)||[]).length===27,'Preservar microdatos SEO');
assert(dir.includes("script-src 'self'")&&dir.includes("connect-src 'self' https://*.supabase.co"),'CSP catálogo incompatible');
assert(app.includes('bn:catalog-updated')&&app.includes('id:s.id'),'El catálogo no está enlazado');
assert(panel.includes('name="robots" content="noindex,nofollow,noarchive"'),'Panel no indexable');
assert(panelJS.includes('/auth/v1/otp')&&panelJS.includes('/auth/v1/verify'),'Autenticación OTP requerida');
assert(panelJS.includes('bn_admin_users?select=user_id'),'Verificación RLS ausente');
assert(panelJS.includes('bn_price_history?select'),'Historial de precios ausente');
assert(!panelJS.includes('localStorage')&&!panelJS.includes('sessionStorage'),'No conservar token en navegador');
assert(cfg.includes('url:""')&&cfg.includes('publishableKey:""'),'No habilitar conexión real sin configuración');
assert(!/sb_secret_|service_role|BEGIN PRIVATE KEY/i.test(cfg),'No publicar claves secretas');
assert(!live.includes('service_role')&&live.includes('No se pudo leer')===false,'Cliente público seguro');
assert(sql.includes('enable row level security')&&sql.includes('bn_services_admin_update'),'Falta RLS');
assert(sql.includes('bn_log_price_changes'),'Falta auditoría');
assert((seed.match(/\('s\d{2}',/g)||[]).length===27,'Importar 27 servicios originales');
for(const f of ['gestion.html','gestion.css','gestion.js','bn-config.js','catalogo-live.js'])assert(build.includes(f),'Falta en el paquete: '+f);
console.log('Panel de gestión: OTP, RLS, 27 servicios, SEO, mapa y fallback OK');
