import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const css=readFileSync(new URL('../styles.css',import.meta.url),'utf8');
const html=readFileSync(new URL('../index.html',import.meta.url),'utf8');
assert(html.includes('content="width=device-width,initial-scale=1"'),'Meta viewport');
assert(css.includes('overflow-x:clip'),'Evitar scroll horizontal');
assert(css.includes('.wrap{width:min(calc(100% - 64px),var(--limit))'),'Contenedor máximo desktop');
assert(css.includes('--limit:1220px'),'Ancho máximo desktop');
for(const rule of ['@media(max-width:380px)','@media(max-width:650px)','@media(max-width:850px)'])assert(css.includes(rule),'Falta breakpoint '+rule);
assert(css.includes('grid-template-columns:repeat(2,minmax(0,1fr))'),'Grilla móvil');
assert(css.includes('.catalog-list'),'Catálogo responsive');
console.log('Contrato de ancho responsive editorial: OK');